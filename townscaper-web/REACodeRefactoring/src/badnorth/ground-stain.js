/**
 * 第 92 轮 · 地面染色（groundTint）—— 837027901853810688 的「打完一场，整岛雪地泛粉」。
 *
 * 为什么单独一个文件：本模块**不 import three**，可以直接被 `node tests/ground-stain.mjs` 纯逻辑测。
 * （r89 的坑：曲线一旦写在依赖 three 的模块里，node 就 import 不了，只能整段复制到测试里。）
 *
 * ── 实测口径（帧 837027901853810688，460×460，32.885 fps，514 帧）
 * 取两个远离火坑的地面窗口（y250–330, x60–175 与 x330–430）逐帧求逐通道中位：
 *
 *   frame   地面左 [R,G,B]      地面右 [R,G,B]      海面 [R,G,B]
 *   0000    [161,167,171]      [154,156,160]      [165,176,178]
 *   0082    [160,164,167]      [154,156,161]      [165,176,178]   ← 起爆前一帧
 *   0100    [161,163,167]      [153,153,158]      [165,176,178]
 *   0300    [160,160,165]      [154,150,156]      [165,176,178]
 *   0510    [161,156,162]      [154,147,154]      [165,176,178]
 *
 * 三条结论定下了实现方式：
 *   ① **不是全局调色/大气**：海面 514 帧恒为 [165,176,178]（r−g 恒 −11）→ 只有陆地变色。
 *   ② **不是「加红」而是「压绿蓝」**：R 通道 161→161 / 154→154 一格没动，G 掉 11 与 9、B 掉 9 与 6
 *      → 乘性系数 (1.000, 0.934, 0.947)，即雪地褪成灰玫瑰。所以染色层用 **MultiplyBlending**，
 *      不是往地面上叠一层半透明粉（那会把暗处提亮，与片子相反）。
 *   ③ **是渐进的、且有台阶**：(r−g) 地面均值 −5.5 → +2.5，中间不是直线：
 *      起爆瞬间（f0083，2.52s）一步跨到 25%，之后每 3s 挪几个点，10.2s 与 10.9s 两帧内冲到 100%。
 */

/** 染色参数：`tint` 是 p=1 时的乘性系数增量（乘性 = 1 + tint·p）。 */
export const GROUND_STAIN = {
  tint: { r: 0.000, g: -0.066, b: -0.053 },
  /**
   * 进度折线（秒 since 第一次伤害 / 0–1）。点全部来自上面那张表：
   * (gndL+gndR)/2 的 r−g 从 −5.5 归一到 0、到结束帧的 +2.5 归一为 1。
   *   2.52s→0.25 / 3.04s→0.31 / 6.08s→0.44 / 9.12s→0.44 / 10.95s→0.69 / 12.77s→0.94 / 13.38s→1.00
   * 再减掉 2.52s 的起点，得到下表。
   */
  ramp: [
    [0.00, 0.00],   // 未受伤：原色
    [0.05, 0.25],   // 起爆一帧内就到 25%（片子是「炸完地面立刻脏一层」，不是慢慢渗）
    [0.52, 0.31],
    [3.56, 0.44],
    [6.60, 0.44],   // 4–7s 平台（这一段时间只有烟雾在动，地面色不动）
    [8.43, 0.69],
    [10.25, 0.94],  // 10.2–10.9s 第二级台阶（对应 f0406 的 −1→+1）
    [10.86, 1.00],
  ],
  /** 全片只到 13.4s 就结束了，之后是否还继续变深片子给不出 → 饱和在 1，不再外推。 */
  saturates: true,
};

/** 纯函数：age 秒时染到几成（0–1）。折线点直返，避免浮点误差让零容差断言永远红。 */
export function stainProgress(age) {
  const t = Number(age);
  if (!Number.isFinite(t) || t <= 0) return 0;
  const r = GROUND_STAIN.ramp;
  for (let i = 0; i < r.length; i++) if (t === r[i][0]) return r[i][1];
  if (t >= r[r.length - 1][0]) return r[r.length - 1][1];
  for (let i = 1; i < r.length; i++) {
    const [t0, v0] = r[i - 1], [t1, v1] = r[i];
    if (t < t1) return v0 + (v1 - v0) * ((t - t0) / (t1 - t0));
  }
  return r[r.length - 1][1];
}

/** 纯函数：p 成染色时的乘性 RGB（p=0 恒 [1,1,1]，p=1 为实测系数）。 */
export function stainTint(p) {
  const k = Math.max(0, Math.min(1, Number(p) || 0)), c = GROUND_STAIN.tint;
  return [1 + c.r * k, 1 + c.g * k, 1 + c.b * k];
}

/** 纯函数：把乘性系数折成 #rrggbb（贴图材质只吃颜色时用）。 */
export function stainHex(p) {
  const [r, g, b] = stainTint(p).map((v) => Math.round(Math.max(0, Math.min(1, v)) * 255));
  return '#' + [r, g, b].map((v) => v.toString(16).padStart(2, '0')).join('');
}
