import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { planChapter } from '../../src/planChapter.mjs';
import { layoutEdena } from '../../src/layoutEdena.mjs';
const root = '/Users/panglaohu/Downloads/TigerInBamboo/CartonBook';
const recipe = JSON.parse(fs.readFileSync(`${root}/recipes/bookshop-letter.sample.json`, 'utf8'));
const dir = `${root}/artifacts/bookshop-review/check-pipeline-output`;
fs.rmSync(dir, { recursive: true, force: true });
const { plan } = planChapter(recipe, { chapterDir: dir });
assert.equal(plan.shots.length, 24);
assert.equal(plan.shots[5].camera.battle, 'start');
assert.equal(plan.shots[5].camera.object, 'bookshop-steampunk-robots');
assert.deepEqual(plan.shots[5].camera.eye, [0, 65, 110]);
assert.equal(plan.shots.find(s => s.id === 's23').camera.object, 'duke-coastal-steam-freighter');
const ids = new Set(plan.shots.map(s => s.id));
assert.equal(ids.size, 24);
const used = plan.pages.flatMap(p => p.panels.map(panel => panel.shotId));
assert.equal(new Set(used).size, 24);
assert.equal(used.length, 24);
layoutEdena(plan, { chapterDir: dir });
const cover = fs.readFileSync(path.join(dir, 'pages/cover.html'), 'utf8');
assert(cover.includes('书不登船。信先过海。'));
assert(cover.includes('cover-spread'));
assert(cover.includes('../../../layouts/edena.css'));
console.log('PASS: 24 shots, real battle trigger, DUKE delivery camera, every shot used once, two-leaf cover, standalone CSS path.');
