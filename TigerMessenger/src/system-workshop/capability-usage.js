/** 没写到的能力：按描述和参数生成说明 */
export function usageFor(item) {
  const u = USAGE[item.id];
  if (u) return u;
  if (item.set) return { what: `能力集合「${item.name}」：一次把 ${item.set.length} 个能力加进管线。`, when: '想快速搭出一条常用管线时。',
    steps: ['把整张卡片拖进上方管线（或双击）', '每个能力会进到它所属的泳道', RUN], example: { goal: item.desc || '', params: '用集合里预设的参数', result: '管线里一次出现所有节点，可以单独调参数或移出。' } };
  if (!item.runnable) return { what: (item.desc || item.name || '').slice(0, 120), when: '现在还不能用：这是学习库里的方法，只在能力库里占位。',
    steps: ['点卡片展开，看来源视频和原版代码位置', '「在学习工坊查看」可以看原帖', '等它重构并封装成能力代码后，卡片变成 ⚙，就能拖进管线'],
    example: { goal: '—', params: '—', result: '占位方法不能执行，所以管线里不放它。' } };
  const params = item.cap?.params ? Object.values(item.cap.params).map((p) => p.label).join('、') : '';
  return { what: (item.desc || item.name || '').slice(0, 140), when: '需要这个效果时。', steps: [DRAG('对应分区'), params ? `调参数：${params}` : '用默认参数', RUN],
    example: { goal: (item.cap?.keywords || []).slice(0, 3).join('、') || '—', params: params || '默认', result: '看验证结果，通过才能写入。' } };
}
